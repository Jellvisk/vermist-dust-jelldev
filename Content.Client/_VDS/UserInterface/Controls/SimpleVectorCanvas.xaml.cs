using System.Linq;
using System.Numerics;
using Robust.Client.AutoGenerated;
using Robust.Client.Graphics;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Timing;

namespace Content.Client._VDS.UserInterface.Controls;

[GenerateTypedNameReferences]
[Virtual]
public partial class SimpleVectorCanvas : Control
{
    [Dependency]
    private readonly IGameTiming _timing = default!;

    private List<SimpleCanvasPoint> _points = [];
    private List<SimpleCanvasLine> _lines = [];

    [ViewVariables(VVAccess.ReadWrite)]
    public List<SimpleCanvasPoint> Points
    {
        get => _points;
        set => _points = value;
    }

    [ViewVariables(VVAccess.ReadWrite)]
    public List<SimpleCanvasLine> Lines
    {
        get => _lines;
        set => _lines = value;
    }

    public void AddPoint(
        Vector2 location,
        float radius,
        string? key
    )
    {
        var point = new SimpleCanvasPoint
        {
            Key = key ?? Name,
            Location = location,
            Radius = radius,
        };

        Points.Add(point);
    }

    public Dictionary<string, SimpleCanvasPoint> GetPointDict()
    {
        var dict = new Dictionary<string, SimpleCanvasPoint>();

        var index = 0;
        foreach (var point in Points)
        {
            // if key is null, just give it its index value.
            dict.Add(point.Key ?? index.ToString(), point);
            index++;
        }

        return dict;
    }

    private TimeSpan _lastUpdate = TimeSpan.Zero;

    public const int StandardSizeFull = 300;
    public const int StandardRadiusCircle = 140;
    public int SizeFull => (int)(StandardSizeFull * UIScale);
    public int RadiusCircle => (int)(StandardRadiusCircle * UIScale);

    public SimpleVectorCanvas()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);
        _points = Points;
        _lines = Lines;
        MinSize = new Vector2(SizeFull, SizeFull);
    }

    public void UpdateState()
    {
        _points = Points;
        _lines = Lines;
        _lastUpdate = _timing.CurTime;
    }

    protected override void Draw(DrawingHandleScreen handle)
    {
        var centerPoint = SizeFull / 2;
        var fakeAA = new Color(0.08f, 0.08f, 0.08f);
        var gridLines = new Color(0.08f, 0.08f, 0.08f);
        var panelExtentCutback = 4;
        var gridLinesRadial = 8;
        var gridLinesEquatorial = 8;

        // Draw base
        handle.DrawCircle(new Vector2(centerPoint, centerPoint), RadiusCircle + 1, fakeAA);
        handle.DrawCircle(new Vector2(centerPoint, centerPoint), RadiusCircle, Color.Black);

        // Draw grid lines
        for (var i = 0; i < gridLinesEquatorial; i++)
        {
            handle.DrawCircle(
                new Vector2(centerPoint, centerPoint),
                (RadiusCircle / gridLinesEquatorial) * i,
                gridLines,
                false
            );
        }

        for (var i = 0; i < gridLinesRadial; i++)
        {
            Angle angle = Math.PI / gridLinesRadial * i;
            var aExtent = angle.ToVec() * RadiusCircle;
            handle.DrawLine(
                new Vector2(centerPoint, centerPoint) - aExtent,
                new Vector2(centerPoint, centerPoint) + aExtent,
                gridLines
            );
        }

        if (_points.Count > 0)
        {
            foreach (var point in _points)
            {
                handle.DrawCircle(point.Location, point.Radius, Color.AliceBlue);
            }
        }

        if (_lines.Count > 0)
        {
            foreach (var line in _lines)
            {
                handle.DrawLine(line.From, line.To, Color.Aqua);
            }
        }
    }
}

[DataDefinition]
public sealed partial class SimpleCanvasPoint
{
    [ViewVariables(VVAccess.ReadWrite)]
    public string? Key { get; set; }

    [ViewVariables(VVAccess.ReadWrite)]
    public Vector2 Location { get; set; }

    [ViewVariables(VVAccess.ReadWrite)]
    public float Radius { get; set; }
}

[DataDefinition]
public sealed partial class SimpleCanvasLine
{
    [ViewVariables(VVAccess.ReadWrite)]
    public string? Key { get; set; }

    [ViewVariables(VVAccess.ReadWrite)]
    public Vector2 From { get; set; }

    [ViewVariables(VVAccess.ReadWrite)]
    public Vector2 To { get; set; }

    [ViewVariables(VVAccess.ReadWrite)]
    public float Width { get; set; }
}
