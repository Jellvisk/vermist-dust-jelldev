using System.Numerics;
using Robust.Client.AutoGenerated;
using Robust.Client.Graphics;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Timing;

namespace Content.Client._VDS.UserInterface.Controls;

[GenerateTypedNameReferences]
[Virtual]
public partial class SimpleVectorCanvas : Control
{
    [Dependency]
    private readonly IGameTiming _timing = default!;

    private TimeSpan _lastUpdate = TimeSpan.Zero;

    private List<ISimpleVectorCanvasData> _vectors = [];
    private List<ISimpleVectorCanvasBrush> _brushes = [];

    private readonly Circle _defaultBrush = new()
    {
        Key = "default",
        Radius = 5,
        Color = Color.White,
        Filled = true,
    };

    /// <summary>
    /// A cache used to loop through each element via their brush key, since a dictionary by key lookup is O(1).
    /// Probably overkill, but if you have a thousand elements, we don't want to swap tools every iteration when we can
    /// just keep drawing the elements that still require the current tool.
    /// </summary>
    private Dictionary<ISimpleVectorCanvasBrush, List<ISimpleVectorCanvasData>>? _vectorsByBrush;

    /// <summary>
    /// Public-facing list of all our <see cref="ISimpleVectorCanvasData"/>s.
    /// If changed, our elements by brush cache will be rebuilt. <see cref="GetVectorsByBrush()"/>.
    /// </summary>
    [ViewVariables(VVAccess.ReadWrite)]
    public List<ISimpleVectorCanvasData> Vectors
    {
        get => _vectors;
        set
        {
            _vectors = value ?? [];
            _vectorsByBrush = null; // elements updated, so the cache is now invalid.
        }
    }

    /// <summary>
    /// Public-facing list of all our <see cref="ISimpleVectorCanvasBrush"/>.
    /// </summary>
    [ViewVariables(VVAccess.ReadWrite)]
    public List<ISimpleVectorCanvasBrush> Brushes
    {
        get => _brushes;
        set => _brushes = value ?? [];
    }

    public const int StandardSizeFull = 300;
    public const int StandardRadiusCircle = 140;
    public int SizeFull => (int)(StandardSizeFull * UIScale);
    public int RadiusCircle => (int)(StandardRadiusCircle * UIScale);

    public SimpleVectorCanvas()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);
        _defaultBrush.AddBrush(this);
        Log.Debug($"init brushes = {Brushes}, init vectors = {Vectors}");
        MinSize = new Vector2(SizeFull, SizeFull);
    }

    public void UpdateState()
    {
        _brushes = Brushes;
        _vectors = Vectors;
        GetVectorsByBrush();
        _lastUpdate = _timing.CurTime;
    }

    protected override void Draw(DrawingHandleScreen handle)
    {
        var centerPoint = SizeFull / 2;
        var fakeAA = new Color(0.08f, 0.08f, 0.08f);
        var gridLines = new Color(0.08f, 0.08f, 0.08f);
        var panelExtentCutback = 4;
        var gridLinesRadial = 8;
        var gridLinesEquatorial = 8;

        // Draw base
        handle.DrawCircle(new Vector2(centerPoint, centerPoint), RadiusCircle + 1, fakeAA);
        handle.DrawCircle(new Vector2(centerPoint, centerPoint), RadiusCircle, Color.Black);

        // Draw grid lines
        for (var i = 0; i < gridLinesEquatorial; i++)
        {
            handle.DrawCircle(
                new Vector2(centerPoint, centerPoint),
                (RadiusCircle / gridLinesEquatorial) * i,
                gridLines,
                false
            );
        }

        for (var i = 0; i < gridLinesRadial; i++)
        {
            Angle angle = Math.PI / gridLinesRadial * i;
            var aExtent = angle.ToVec() * RadiusCircle;
            handle.DrawLine(
                new Vector2(centerPoint, centerPoint) - aExtent,
                new Vector2(centerPoint, centerPoint) + aExtent,
                gridLines
            );
        }

        var vectorsByBrush = GetVectorsByBrush();
        if (vectorsByBrush?.Count > 0)
        {
            foreach (var (brush, vectors) in vectorsByBrush)
            {
                brush.DrawStrokes(this, vectors, handle);
            }
        }
    }

    public Dictionary<ISimpleVectorCanvasBrush, List<ISimpleVectorCanvasData>> GetVectorsByBrush()
    {
        if (_vectorsByBrush is not null)
            return _vectorsByBrush;
        // if null, we need to rebuild

        var dict = new Dictionary<ISimpleVectorCanvasBrush, List<ISimpleVectorCanvasData>>(_vectors.Count);
        var brush = Brushes[0]; // avoid getting a new brush every loop if possible

        foreach (var vector in _vectors)
        {
            if (vector.BrushKey != brush.Key)
                brush = GetBrushByBrushKey(vector.BrushKey);

            // get the canvas data list for this brush. list will always be provided, empty or not.
            if (!dict.TryGetValue(brush, out var list))
            {
                list = []; // initialize list if there is no values
                dict[brush] = list; // add list to dictionary that we be returning
            }

            list.Add(vector);
        }
        _vectorsByBrush = dict;
        Log.Debug($"vectors by brush: {_vectorsByBrush}");
        return _vectorsByBrush;
    }

    public ISimpleVectorCanvasBrush GetBrushByBrushKey(string brushKey)
    {
        foreach (var brush in Brushes)
        {
            if (brush.Key == brushKey)
                return brush;
        }

        throw new InvalidOperationException($"Brush '{brushKey}' does not exist.");
    }
}

[Virtual]
public abstract class SimpleVectorCanvasBrush : ISimpleVectorCanvasBrush, IEquatable<ISimpleVectorCanvasBrush>
{
    [ViewVariables(VVAccess.ReadWrite)]
    public abstract string Key { get; set; }

    public void AddBrush(SimpleVectorCanvas canvas)
    {
        canvas.Brushes.Add(this);
    }

    public bool Equals(ISimpleVectorCanvasBrush? other)
    {
        return Key == other?.Key;
    }

    public abstract void DrawStroke(
        SimpleVectorCanvas canvas,
        ISimpleVectorCanvasData element,
        DrawingHandleScreen handle
    );

    public virtual void DrawStrokes(
        SimpleVectorCanvas canvas,
        IEnumerable<ISimpleVectorCanvasData> elements,
        DrawingHandleScreen handle
    )
    {
        foreach (var element in elements)
        {
            DrawStroke(canvas, element, handle);
        }
    }
}

/// <summary>
/// Contract that states this is a brush belonging to some form of element.
/// </summary>
[ImplicitDataDefinitionForInheritors]
public partial interface ISimpleVectorCanvasBrush
{
    [ViewVariables(VVAccess.ReadWrite)]
    string Key { get; set; }

    [ViewVariables(VVAccess.ReadWrite)]
    void AddBrush(SimpleVectorCanvas canvas);

    void DrawStroke(SimpleVectorCanvas canvas, ISimpleVectorCanvasData vector, DrawingHandleScreen handle);

    void DrawStrokes(
        SimpleVectorCanvas canvas,
        IEnumerable<ISimpleVectorCanvasData> vectors,
        DrawingHandleScreen handle
    );
}

/// <summary>
/// Simple circle brush, wrapper for <see cref="DrawingHandleScreen.DrawCircle(Vector2, float, Color, bool)"/>.
/// </summary>
[DataDefinition]
public sealed partial class Circle : SimpleVectorCanvasBrush
{
    [ViewVariables(VVAccess.ReadWrite)]
    public override string Key { get; set; } = "circle";

    [ViewVariables(VVAccess.ReadWrite)]
    public float Radius { get; set; }

    [ViewVariables(VVAccess.ReadWrite)]
    public Color Color { get; set; }

    [ViewVariables(VVAccess.ReadWrite)]
    public bool Filled { get; set; }

    public override void DrawStroke(
        SimpleVectorCanvas canvas,
        ISimpleVectorCanvasData vector,
        DrawingHandleScreen handle
    )
    {
        var pos = vector.GetPosition();
        if (pos.Count < 1)
            return;

        switch (pos.Count)
        {
            case 1:
                handle.DrawCircle(pos[0], Radius, Color, Filled);
                break;
            case > 1:
                for (var count = 0; count < pos.Count; count++)
                {
                    handle.DrawCircle(pos[count], Radius, Color, Filled);
                }
                break;
            default:
                throw new InvalidOperationException();
        }
    }
}

