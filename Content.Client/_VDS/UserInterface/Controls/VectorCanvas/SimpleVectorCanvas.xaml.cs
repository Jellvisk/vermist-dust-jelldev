/// <summary>
/// A straight line of vectors.
/// </summary>
[DataDefinition]
public sealed partial class SimpleVectorCanvasLine : SimpleVectorCanvasData
{
    /// <summary>
    /// Our starting vector.
    /// </summary>
    [ViewVariables(VVAccess.ReadWrite)]
    public Vector2 From { get; set; }

    /// <summary>
    /// Vector to point towards.
    /// </summary>
    [ViewVariables(VVAccess.ReadWrite)]
    public Vector2 To { get; set; }

    /// <summary>
    /// How many extra vectors to draw between From and To.
    /// </summary>
    [ViewVariables(VVAccess.ReadWrite)]
    public int Steps { get; set; }

    private Vector2[] GetStepped()
    {
        if (Steps <= 2)
            return [From, To];

        var result = new Vector2[Steps];
        for (var step = 0f; step < Steps; step++)
        {
            var percent = step / (Steps - 1);
            result[(int)step] = Vector2.Lerp(From, To, percent);
        }

        return result;
    }

    public override IReadOnlyList<Vector2> GetPosition()
    {
        return GetStepped();
    }
}
