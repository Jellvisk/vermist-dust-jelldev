        get => _brushes;
        set => _brushes = value ?? [];
    }

    public VectorCanvas()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);
        _defaultBrush.AddBrush(this);
        // UpdateState();
    }

    [PublicAPI]
    public void UpdateState()
    {
        var vectorsByBrush = GetSlotsByBrush();
        if (vectorsByBrush?.Count > 0)
        {
            foreach (var (brush, vectors) in vectorsByBrush)
            {
                if (brush is BrushControl brushControl)
                    brushControl.AddControls(this, vectors);
            }
        }
        _lastUpdate = _timing.CurTime;
    }

    protected override void Draw(DrawingHandleScreen handle)
    {
        var vectorsByBrush = GetSlotsByBrush();
        if (vectorsByBrush?.Count > 0)
        {
            foreach (var (brush, vectors) in vectorsByBrush)
            {
                if (brush is IVectorCanvasPainter painter)
                    painter.DrawStrokes(this, vectors, handle);
            }
        }
    }

