    /// <summary>
    /// Update and get all canvas slots, key'd by the brush they request.
    /// </summary>
    /// <returns>A dictionary where every slot is key'd by the brush they wish to be drawn by./returns>
    public Dictionary<IVectorCanvasBrush, List<IVectorCanvasSlot>> GetSlotsByBrush()
    {
        if (_slotsByBrush is not null)
            return _slotsByBrush;
        // if null, we need to rebuild

        if (_slots.Count == 0)
        {
            _slotsByBrush = [];
            return [];
        }

        var dict = new Dictionary<IVectorCanvasBrush, List<IVectorCanvasSlot>>(_slots.Count);
        // var brush = Brushes[0]; // avoid getting a new brush every loop if possible
        var brushes = GetBrushesByBrushKey(_slots[0].BrushKey);

        foreach (var vector in _slots)
        {
            if (brushes.All(brush => vector.BrushKey != brush.Key))
                brushes = GetBrushesByBrushKey(vector.BrushKey);

            // get the canvas data list for this brush. list will always be provided, empty or not.
            foreach (var brush in brushes)
            {
                if (!dict.TryGetValue(brush, out var vectorList))
                {
                    vectorList = []; // initialize list if there is no values
                    dict[brush] = vectorList; // add list to dictionary that we be returning
                }

                vectorList.Add(vector);
            }
        }

        _slotsByBrush = dict;
        return _slotsByBrush;
    }

    /// <summary>
    /// Return an <see cref="IVectorCanvasBrush"/> by its key.
    /// </summary>
    /// <param name="brushKey">The brush key to look for.</param>
    /// <returns>The first <see cref="IVectorCanvasBrush"/> found matching <paramref name="brushKey"/></returns>
    /// <exception cref="InvalidOperationException">The brush key does not exist.</exception>
    public IVectorCanvasBrush GetBrushByBrushKey(string brushKey)
    {
        foreach (var brush in Brushes)
        {
            if (brush.Key == brushKey)
                return brush;
        }

        throw new InvalidOperationException($"Brush '{brushKey}' does not exist.");
    }

    public List<IVectorCanvasBrush> GetBrushesByBrushKey(string brushKey)
    {
        var brushes = new List<IVectorCanvasBrush>();
        foreach (var brush in Brushes)
        {
            if (brush.Key == brushKey)
                brushes.Add(brush);
        }

        if (brushes.Count > 0)
            return brushes;

        throw new InvalidOperationException($"Brush '{brushKey}' does not exist.");
    }

