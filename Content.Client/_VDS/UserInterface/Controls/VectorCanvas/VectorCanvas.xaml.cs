    }

    public enum SlotScaleType : byte
    {

        /// <summary>
        /// Keep slot proportions and position. Scale X/Y will match altered canvas/UI scale.
        /// </summary>
        Fixed,

        /// <summary>
        /// Stretch/squash slot X and Y to fit altered canvas size.
        /// Utilizes <see cref="IVectorCanvasSlot.SlotMinScale"/> & <see cref="IVectorCanvasSlot.SlotMaxScale"/>.
        /// </summary>
        Stretch,

        /// <summary>
        /// Move slot X and Y by its <see cref="IVectorCanvasSlot.SlotElasticity"/> percent to fit altered canvas size.
        /// </summary>
        Elastic,

        /// <summary>
        /// Stretch + Elastic
        /// </summary>
        Free
    }
