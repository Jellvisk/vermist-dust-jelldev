    /// <summary>
    /// Public-facing list of all our <see cref="IVectorCanvasSlot"/>s.
    /// If changed, our elements by brush cache will be rebuilt. <see cref="GetSlotsByBrush()"/>.
    /// </summary>
    [ViewVariables(VVAccess.ReadWrite)]
    public List<IVectorCanvasSlot> Slots
    {
        get => _slots;
        set
        {
            _slots = value ?? [];
            _slotsByBrush = null; // elements updated, so the cache is now invalid.
        }
    }

    /// <summary>
    /// Public-facing list of all our <see cref="IVectorCanvasBrush"/>.
    /// </summary>
    [ViewVariables(VVAccess.ReadWrite)]
    public List<IVectorCanvasBrush> Brushes
